import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { readAuthoredPolitics, legacyDefault, validateAuthoredPolitics } from './politics-default';
import { validateSnapshot, type SnapshotKind } from '../../src/lib/workspaces/data';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const check = process.argv.includes('--check');
const hash = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');
const descriptors: Record<string, unknown> = {};
let politics;
for (const [kind, name] of [['politics', 'politics-static'], ['regional-er', 'regional-er-static']]) {
  const path = `data/v1/${name}.json`, bytes = await readFile(resolve(root, 'web/static', path));
  const snapshot = JSON.parse(bytes.toString());
  validateSnapshot(kind as SnapshotKind, snapshot, snapshot.metadata.schema_version);
  const digest = hash(bytes);
  descriptors[kind] = { path, bytes: bytes.length, sha256: digest, schemaVersion: snapshot.metadata.schema_version, version: `${kind}:${digest}` };
  if (kind === 'politics') politics = snapshot;
}
const authored = await readAuthoredPolitics(root);
await validateAuthoredPolitics(authored, { implementationId: 'packaging',
  asset: async pin => new Uint8Array(await readFile(resolve(root, 'web/static', pin.uri))),
  sourceChunk: async () => { throw new Error('Descriptor generation does not read historical observation chunks'); } });
const source = JSON.parse(await readFile(resolve(root, 'web/static', authored.data.historical.uri), 'utf8'));
const defaults = legacyDefault(authored, politics, source, (descriptors.politics as { version: string }).version);
const descriptorText = `// Generated by npm run data:workspaces:generate. Do not edit.\nimport type { SnapshotDescriptor } from './data';\nexport const snapshotDescriptors: Partial<Record<'politics' | 'regional-er', SnapshotDescriptor>> = ${JSON.stringify(descriptors, null, 2)};\n`;
const defaultsText = `// Generated by npm run data:workspaces:generate. Do not edit.\nimport type { Scenario } from '$lib/core/types';\nexport const generatedDefaultPoliticsScenario = ${JSON.stringify(defaults, null, 2)} satisfies Scenario;\n`;
for (const [path, text] of [['web/src/lib/workspaces/snapshots.generated.ts', descriptorText], ['web/src/lib/scenario/politics-defaults.generated.ts', defaultsText]]) {
  if (check) { if (await readFile(resolve(root, path), 'utf8') !== text) throw new Error(`Regenerate workspace data: ${path}`); }
  else await writeFile(resolve(root, path), text);
}
console.log(`Workspace data ${check ? 'verified' : 'generated'}: politics and Emilia-Romagna.`);
