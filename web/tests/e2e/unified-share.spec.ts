import { archiveDigest } from '../fixtures/archive-digest';
import { test, expect } from '@playwright/test';
import { productionWorkflowMs, waitForPoliticsReady } from '../fixtures/politics-readiness';
import { mkdir, writeFile, stat } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openCommon, openResultTransfers, runCommon, selectedCommon, base } from '../fixtures/common-page';
import { ROSATELLUM, REFORM } from '../../src/lib/politics/scenario/schema';
const draws = Number(process.env.FV08_DRAWS ?? 3);
if (!Number.isSafeInteger(draws) || draws < 1 || draws > 1000)
    throw new Error('Acceptance supports 1–1000 draws');
test.setTimeout(productionWorkflowMs);
for (const [law, model] of [[ROSATELLUM, 'M01'], [ROSATELLUM, 'M02'], [REFORM, 'M01'], [REFORM, 'M02']] as const)
    test(`${law}/${model} unified browser workflow`, async ({ page, browser }) => {
        const errors: string[] = [];
        page.on('pageerror', e => errors.push(e.message));
        const initial = await openCommon(page, law, model, draws), before = await runCommon(page);
        expect(before.result.completedSimulations).toBe(draws);
        expect(before.politics.run.session.simulations).toEqual(Array.from({ length: draws }, (_, i) => ({ id: i + 1, outcome: 'complete' })));
        expect(before.result.storage.maxChunkBytes).toBeLessThanOrEqual(256 * 1024);
        expect(before.politics.run.execution.actualWorkers).toBe(Math.min(2, draws));
        const directory = resolve(process.env.ACCEPTANCE_ARCHIVE_OUTPUT ?? '../data/derived/cp08-browser');
        await mkdir(directory, { recursive: true });
        const archive = resolve(directory, `${browser.browserType().name()}-${law}-${model}-${base ? 'project' : 'root'}.json.gz`);
        const download = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Scarica archivio risultati JSON.gz', exact: true }).click();
        await (await download).saveAs(archive);
        await page.getByLabel('Nome scenario', { exact: true }).fill('Unchanged draft during result import');
        await page.getByLabel('Nome scenario', { exact: true }).blur();
        await page.getByLabel('Importa risultati', { exact: true }).setInputFiles(archive);
        await openResultTransfers(page);
        await expect(page.getByRole('combobox', { name: 'Sessione dei risultati', exact: true })).not.toHaveValue(before.id, { timeout: 60000 });
        const after = await selectedCommon(page);
        expect(after.politics.run.session.simulations).toEqual(before.politics.run.session.simulations);
        expect(after.politics.run.execution).toEqual(before.politics.run.execution);
        await expect(page.getByLabel('Nome scenario', { exact: true })).toHaveValue('Unchanged draft during result import');
        const reexport = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Scarica archivio risultati JSON.gz', exact: true }).click();
        await (await reexport).saveAs(archive + '.roundtrip.gz');
        const content = await archiveDigest(archive);
        expect(await archiveDigest(archive + '.roundtrip.gz')).toEqual(content);
        const csv = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Scarica risultati CSV', exact: true }).click();
        expect((await (await csv).createReadStream()) !== null).toBe(true);
        await page.reload();
        await openResultTransfers(page);
        await expect(page.getByRole('combobox', { name: 'Sessione dei risultati', exact: true })).toHaveValue(after.id);
        await page.getByRole('button', { name: 'Carica lo scenario di questa sessione', exact: true }).click();
        await expect(page.getByLabel('Nome scenario', { exact: true })).toHaveValue(initial.name);
        await waitForPoliticsReady(page);
        await expect(page.getByLabel('Seed delle simulazioni', { exact: true })).toHaveValue(initial.execution.simulationSeed);
        await writeFile(archive + '.receipt.json', JSON.stringify({ base, browser: browser.version(), law, model, draws, execution: before.politics.run.execution, storage: before.result.storage, content, archiveBytes: (await stat(archive)).size, errors }, null, 2));
        expect(errors).toEqual([]);
    });
